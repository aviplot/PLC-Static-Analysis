// Writes src/monaco.ts: Monaco's editor API with the editor features of editor.main.js, without its language
// definitions, language workers (TS, CSS, HTML, JSON) and LSP client. Run after a Monaco upgrade:
// node scripts/monaco-features.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const main = readFileSync('node_modules/monaco-editor/esm/vs/editor/editor.main.js', 'utf8');
const features = main
  .split('\n')
  .filter((l) => /^import '\.\/|^import '\.\.\/(base|features|platform)/.test(l))
  .map((l) => l.replace(/'(\.\.?\/[^']+)'/, (_, p) => `'monaco-esm/${new URL(p, 'file:///editor/').pathname.slice(1)}'`));
writeFileSync(
  'src/monaco.ts',
  `// Generated by scripts/monaco-features.mjs from monaco-editor's editor.main.js: the editor and its features,
// no bundled languages or language workers.
${features.join('\n')}
export * from 'monaco-esm/editor/editor.api.js';
`,
);
console.log(`src/monaco.ts: ${features.length} feature imports`);
