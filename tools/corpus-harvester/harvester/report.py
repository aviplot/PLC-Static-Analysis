"""Dedup + MANIFEST.csv / STATS.md / SOURCES.md generation."""

from __future__ import annotations

import csv
import datetime as dt
import logging
from collections import Counter, defaultdict
from pathlib import Path

from . import classify, licenses
from .state import State

log = logging.getLogger("harvester.report")

DIALECTS = [classify.CODESYS, classify.TWINCAT, classify.SIEMENS, classify.ROCKWELL, classify.PLCOPEN]
LANGUAGE_OF = {  # dialect -> CLAUDE.md language number
    classify.CODESYS: "1 CODESYS ST", classify.TWINCAT: "1 CODESYS ST (TwinCAT)",
    classify.SIEMENS: "2 Siemens SCL", classify.ROCKWELL: "3 Rockwell L5X", classify.PLCOPEN: "4 PLCopen XML",
}
MANIFEST_COLUMNS = ["repo_url", "commit_sha", "path", "dialect", "format", "spdx_license", "policy",
                    "size_bytes", "lines", "sha256"]
FEW_REPOS = 5


def dedup(state: State, external: Path) -> list[tuple[dict, dict]]:
    """First copy in discovery order wins; later copies are deleted from disk."""
    seen: set[str] = set()
    kept, removed = [], 0
    for rec in sorted(state.repos.values(), key=lambda r: r["order"]):
        if rec.get("status") != "done":
            continue
        for f in rec.get("files", []):
            local = external / rec["host"] / rec["full_name"] / f["path"]
            if not local.exists():
                f["dup"] = True
                continue
            if f["sha256"] in seen:
                local.unlink()
                f["dup"] = True
                removed += 1
                continue
            seen.add(f["sha256"])
            f["dup"] = False
            kept.append((rec, f))
    _prune_empty_dirs(external)
    state.data["dups_removed_total"] = state.data.get("dups_removed_total", 0) + removed
    state.save()
    log.info("dedup: kept %d unique files, removed %d duplicates this run", len(kept), removed)
    return kept


def _prune_empty_dirs(root: Path) -> None:
    for d in sorted((p for p in root.rglob("*") if p.is_dir()), key=lambda p: len(p.parts), reverse=True):
        try:
            d.rmdir()
        except OSError:
            pass


def write_manifest(kept: list[tuple[dict, dict]], path: Path) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(MANIFEST_COLUMNS)
        for rec, f in kept:
            lic = rec.get("license") or licenses.NOASSERTION
            w.writerow([rec["html_url"], rec["sha"], f["path"], f["dialect"], f["format"], lic,
                        licenses.policy(lic), f["size"], f["lines"], f["sha256"]])


def _table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def write_stats(state: State, kept: list[tuple[dict, dict]], path: Path) -> None:
    by_dialect = defaultdict(lambda: [0, 0, set()])
    by_format = defaultdict(lambda: [0, 0])
    by_license = defaultdict(lambda: [0, 0, set()])
    by_policy = defaultdict(lambda: [0, 0])
    by_repo = defaultdict(lambda: [0, 0, None, set()])
    for rec, f in kept:
        lic = rec.get("license") or licenses.NOASSERTION
        d = by_dialect[f["dialect"]]; d[0] += 1; d[1] += f["lines"]; d[2].add(rec["html_url"])
        fm = by_format[f["format"]]; fm[0] += 1; fm[1] += f["lines"]
        lc = by_license[lic]; lc[0] += 1; lc[1] += f["lines"]; lc[2].add(rec["html_url"])
        p = by_policy[licenses.policy(lic)]; p[0] += 1; p[1] += f["lines"]
        r = by_repo[rec["html_url"]]; r[0] += 1; r[1] += f["lines"]; r[2] = lic; r[3].add(f["dialect"])

    repos = state.repos.values()
    status = Counter(r.get("status") for r in repos)
    hosts = Counter(r["host"] for r in repos)
    with_files = sum(1 for r in repos if r.get("status") == "done" and r.get("files"))
    truncated = sorted(k for k, q in state.queries.items() if q.get("truncated") and not q.get("split"))
    total_files = sum(v[0] for v in by_dialect.values())
    total_lines = sum(v[1] for v in by_dialect.values())

    s = [f"# Corpus statistics\n",
         f"Generated by `tools/corpus-harvester` on {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC. "
         f"Raw files live in `corpus/external/` (git-ignored); see `MANIFEST.csv` for per-file provenance.\n",
         "## Summary\n",
         _table(["", "count"], [
             ["unique files", f"{total_files:,}"],
             ["lines", f"{total_lines:,}"],
             ["repos contributing files", f"{with_files:,}"],
             ["candidate repos discovered", f"{len(state.repos):,} ("
              + ", ".join(f"{h}: {n}" for h, n in sorted(hosts.items())) + ")"],
             ["repos fetched / failed / skipped / pending",
              f"{status['done']} / {status['failed']} / {status['skipped']} / {status['pending']}"],
             ["duplicate files removed (content hash)", f"{state.data.get('dups_removed_total', 0):,}"],
         ]), "",
         "## Per dialect\n",
         _table(["dialect", "language", "files", "lines", "repos"],
                [[d, LANGUAGE_OF[d], f"{by_dialect[d][0]:,}", f"{by_dialect[d][1]:,}", len(by_dialect[d][2])]
                 for d in DIALECTS]), "",
         "## Per format\n",
         _table(["format", "files", "lines"],
                [[k, f"{v[0]:,}", f"{v[1]:,}"] for k, v in sorted(by_format.items(), key=lambda kv: -kv[1][1])]), "",
         "## Per license policy\n",
         _table(["policy", "files", "lines"],
                [[k, f"{v[0]:,}", f"{v[1]:,}"] for k, v in sorted(by_policy.items())]), "",
         "`fixture-ok` = permissive (" + ", ".join(sorted(licenses.PERMISSIVE)) + "): may be used for small "
         "committed fixtures with attribution. `local-only` = copyleft/other/no license: analysis and "
         "benchmarking only, never committed.\n",
         "## Per license\n",
         _table(["SPDX", "files", "lines", "repos"],
                [[k, f"{v[0]:,}", f"{v[1]:,}", len(v[2])]
                 for k, v in sorted(by_license.items(), key=lambda kv: -kv[1][1])]), "",
         "## Top 25 repos by lines\n",
         _table(["repo", "license", "dialects", "files", "lines"],
                [[u, v[2], ", ".join(sorted(v[3])), f"{v[0]:,}", f"{v[1]:,}"]
                 for u, v in sorted(by_repo.items(), key=lambda kv: -kv[1][1])[:25]]), "",
         "## Gaps\n"]

    gaps = []
    for d in DIALECTS:
        n_repos = len(by_dialect[d][2])
        if n_repos == 0:
            gaps.append(f"- **{d}: no real code found.** Plan: synthetic files written against the documented "
                        f"export format, plus self-made exports where a free IDE exists.")
        elif n_repos < FEW_REPOS:
            gaps.append(f"- **{d}: only {n_repos} repo(s)** — low diversity; supplement with synthetic files.")
        fixture_ok = sum(1 for rec, f in kept if f["dialect"] == d
                         and licenses.policy(rec.get("license")) == licenses.FIXTURE_OK)
        if by_dialect[d][0] and fixture_ok == 0:
            gaps.append(f"- {d}: no permissively licensed files — committed fixtures must be hand-written.")
    if truncated:
        gaps.append(f"- {len(truncated)} search quer(ies) exceeded the API's 1000-result cap and were truncated: "
                    + ", ".join(f"`{q}`" for q in truncated[:10]) + ("…" if len(truncated) > 10 else ""))
    if state.data.get("budget_stop"):
        gaps.append(f"- Fetch stopped early: {state.data['budget_stop']}; {status['pending']} repos still pending "
                    f"(re-run `fetch` with a larger budget to continue).")
    if status["failed"]:
        gaps.append(f"- {status['failed']} repos failed to fetch (see checkpoint for errors).")
    too_big = sum(r.get("skipped_too_big", 0) for r in repos)
    if too_big:
        gaps.append(f"- {too_big} candidate files skipped as larger than the per-file size cap.")
    gaps.append("- Code search only indexes default branches and files < 384 KB; very large L5X/PLCopen exports "
                "are found only via repo search.")
    s.append("\n".join(gaps) + "\n")
    path.write_text("\n".join(s), encoding="utf-8")


def write_sources(kept: list[tuple[dict, dict]], path: Path) -> None:
    repos: dict[str, list] = {}
    for rec, f in kept:
        e = repos.setdefault(rec["html_url"], [rec, 0, Counter()])
        e[1] += 1
        e[2][f["dialect"]] += 1
    groups = defaultdict(list)
    for url, (rec, n, dial) in repos.items():
        lic = rec.get("license") or licenses.NOASSERTION
        groups[licenses.policy(lic)].append([f"[{rec['full_name']}]({url})", f"`{rec['sha'][:12]}`", lic,
                                             ", ".join(f"{d} {c}" for d, c in dial.most_common()), n])
    s = ["# Corpus sources\n",
         "Every third-party repository the harvester took files from, with the commit and the license "
         "reported by the host's license API. Generated; do not edit by hand.\n",
         "Policy (CLAUDE.md): only **fixture-ok** sources may be copied into committed fixtures, and each "
         "such fixture must name its source here. **local-only** sources are for local analysis and "
         "benchmarking; never commit, bundle or copy them.\n",
         "## Fixtures committed to this repo\n",
         "None yet.\n"]
    for pol in (licenses.FIXTURE_OK, licenses.LOCAL_ONLY):
        rows = sorted(groups.get(pol, []), key=lambda r: r[0].lower())
        s += [f"## {pol} ({len(rows)} repos)\n",
              _table(["repo", "commit", "license", "files by dialect", "files"], rows) if rows else "None.", ""]
    path.write_text("\n".join(s), encoding="utf-8")


def run(state: State, external: Path, corpus: Path) -> None:
    kept = dedup(state, external)
    write_manifest(kept, corpus / "MANIFEST.csv")
    write_stats(state, kept, corpus / "STATS.md")
    write_sources(kept, corpus / "SOURCES.md")
    log.info("wrote MANIFEST.csv, STATS.md, SOURCES.md in %s", corpus)
